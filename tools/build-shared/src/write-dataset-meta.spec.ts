import { mkdtempSync, mkdirSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { describe, it, beforeEach, afterEach, expect, assert } from 'vitest';

import { writeDatasetMeta } from './write-dataset-meta.js';

let sandbox: string;
const originalLog = console.log;

beforeEach(() => {
  sandbox = mkdtempSync(join(tmpdir(), 'write-dataset-meta-'));
  mkdirSync(join(sandbox, 'data'));
  console.log = () => undefined;
});

afterEach(() => {
  rmSync(sandbox, { recursive: true, force: true });
  console.log = originalLog;
});

/** Standard options, matching what a NASR-backed build tool passes. */
function options(properties: object = { generatedAt: '2026-04-16T00:00:00.000Z', recordCount: 3 }) {
  return {
    constName: 'usBundledWidgetsProperties',
    typeName: 'WidgetDatasetProperties',
    datasetName: 'widget',
    generatedBy: 'tools/build-widget-data',
    properties,
  };
}

describe('writeDatasetMeta', () => {
  it('writes the module next to the package source, not next to the data file', async () => {
    await writeDatasetMeta(join(sandbox, 'data', 'widgets.json.gz'), options());

    const written = readFileSync(join(sandbox, 'src', 'meta.ts'), 'utf-8');
    assert(written.length > 0);
  });

  it('emits a typed constant carrying every metadata field in order', async () => {
    await writeDatasetMeta(
      join(sandbox, 'data', 'widgets.json.gz'),
      options({
        generatedAt: '2026-04-16T00:00:00.000Z',
        nasrCycleDate: '2026-04-16',
        recordCount: 42,
      }),
    );

    const written = readFileSync(join(sandbox, 'src', 'meta.ts'), 'utf-8');
    expect(written).toContain("import type { WidgetDatasetProperties } from './node.js';");
    expect(written).toContain(
      'export const usBundledWidgetsProperties: WidgetDatasetProperties = {',
    );
    expect(written).toContain("  generatedAt: '2026-04-16T00:00:00.000Z',");
    expect(written).toContain("  nasrCycleDate: '2026-04-16',");
    expect(written).toContain('  recordCount: 42,');
    expect(written).toContain('Generated by `tools/build-widget-data`. Do not edit by hand.');
  });

  it('names the dataset in the generated doc comment', async () => {
    await writeDatasetMeta(join(sandbox, 'data', 'widgets.json.gz'), options());

    const written = readFileSync(join(sandbox, 'src', 'meta.ts'), 'utf-8');
    expect(written).toContain('Build metadata for the bundled widget snapshot');
  });

  it('creates the source directory when it does not exist yet', async () => {
    await writeDatasetMeta(join(sandbox, 'nested', 'data', 'widgets.json.gz'), options());

    const written = readFileSync(join(sandbox, 'nested', 'src', 'meta.ts'), 'utf-8');
    assert(written.includes('usBundledWidgetsProperties'));
  });

  it('overwrites a previously generated module', async () => {
    await writeDatasetMeta(join(sandbox, 'data', 'widgets.json.gz'), options({ recordCount: 1 }));
    await writeDatasetMeta(join(sandbox, 'data', 'widgets.json.gz'), options({ recordCount: 2 }));

    const written = readFileSync(join(sandbox, 'src', 'meta.ts'), 'utf-8');
    expect(written).toContain('  recordCount: 2,');
    expect(written).not.toContain('  recordCount: 1,');
  });

  it('rejects a non-primitive metadata value rather than emitting broken source', async () => {
    // Emitting `[object Object]` into a typed constant would produce a file
    // that fails to compile long after the build reported success.
    await expect(
      writeDatasetMeta(
        join(sandbox, 'data', 'widgets.json.gz'),
        options({ nested: { oops: true } }),
      ),
    ).rejects.toThrow(/must be a string or number/);
  });

  it('rejects a string value that would break out of its quotes', async () => {
    await expect(
      writeDatasetMeta(join(sandbox, 'data', 'widgets.json.gz'), options({ label: "it's broken" })),
    ).rejects.toThrow(/single quote/);
  });
});

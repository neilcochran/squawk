import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

/**
 * Inputs describing the metadata module to emit for a data package.
 */
export interface DatasetMetaOptions {
  /** Exported constant name, e.g. `"usBundledAirportsProperties"`. */
  constName: string;
  /** Properties interface the constant is typed as, e.g. `"AirportDatasetProperties"`. */
  typeName: string;
  /** Human-readable dataset name used in the generated doc comment, e.g. `"airport"`. */
  datasetName: string;
  /** Build tool that owns this file, e.g. `"tools/build-airport-data"`. */
  generatedBy: string;
  /**
   * The metadata values themselves, emitted in the order the keys appear.
   *
   * Typed as `object` rather than a record of primitives because each data
   * package declares its own properties interface, and an interface does not
   * satisfy an index-signature constraint in TypeScript. Values are checked
   * as they are serialized instead.
   */
  properties: object;
}

/**
 * Serializes one metadata value as a TypeScript literal.
 *
 * @param key - Field name, used only to describe a rejected value.
 * @param value - Metadata value to emit.
 * @returns The value as TypeScript source.
 * @throws {TypeError} when the value is not a string or number, or is a
 *         string containing a single quote. Dataset metadata is flat
 *         primitives by construction, so either case means the build tool
 *         passed something this generator was never meant to emit.
 */
function serializeValue(key: string, value: unknown): string {
  if (typeof value === 'number') {
    return String(value);
  }
  if (typeof value !== 'string') {
    throw new TypeError(
      `Dataset metadata field "${key}" must be a string or number, got ${typeof value}`,
    );
  }
  if (value.includes("'")) {
    throw new TypeError(`Dataset metadata field "${key}" contains a single quote: ${value}`);
  }
  return `'${value}'`;
}

/**
 * Writes a data package's `src/meta.ts`, a generated module exporting the
 * snapshot's build metadata as a plain constant.
 *
 * The point is to make provenance readable without paying for the snapshot:
 * the metadata inside the `.gz` cannot be reached without decompressing and
 * parsing every record, so a consumer that only wants to report which cycle
 * it is serving would otherwise have to load the whole dataset. Emitting the
 * same values as source keeps that answer free, and keeps it isomorphic -
 * there is no file read, so the Node and browser entries behave alike.
 *
 * The module is located by navigating up one directory from the output data
 * file path (e.g. `packages/libs/airport-data/data/airports.json.gz` resolves
 * to `packages/libs/airport-data/src/meta.ts`).
 *
 * Unlike {@link updateReadmeDate} this is not best-effort: the generated
 * module is part of the package's compiled surface, so failing to write it
 * would ship a snapshot whose metadata silently disagrees with its records.
 *
 * @param outputPath - Absolute path to the data file that was just written.
 * @param options - Names and values to emit.
 */
export async function writeDatasetMeta(
  outputPath: string,
  options: DatasetMetaOptions,
): Promise<void> {
  const metaPath = resolve(dirname(outputPath), '..', 'src', 'meta.ts');
  const fields = Object.entries(options.properties)
    .map(([key, value]: [string, unknown]) => `  ${key}: ${serializeValue(key, value)},`)
    .join('\n');

  const source = `/**
 * @packageDocumentation
 * Build metadata for the bundled ${options.datasetName} snapshot, exposed on its own
 * so consumers can report which cycle they are serving without decompressing
 * the records.
 *
 * Generated by \`${options.generatedBy}\`. Do not edit by hand.
 */

import type { ${options.typeName} } from './node.js';

/** Build metadata for the bundled ${options.datasetName} snapshot. */
export const ${options.constName}: ${options.typeName} = {
${fields}
};
`;

  await mkdir(dirname(metaPath), { recursive: true });
  await writeFile(metaPath, source, 'utf-8');
  console.log(`[write-output] Wrote ${metaPath}`);
}
